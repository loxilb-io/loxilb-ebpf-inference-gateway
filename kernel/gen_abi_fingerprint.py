#!/usr/bin/env python3
"""Generate the shared-header hash, independent of paths and timestamps."""

import argparse
import hashlib
import re
from pathlib import Path


EXCLUDED_HEADERS = {
    "vmlinux.h",
    "llb_abi_fingerprint.generated.h",
    "llb_nat_map_abi.h",
    "llb_map_abi.h",
    "llb_map_abi_table.h",
}


def shared_inputs(kernel_dir):
    roots = (kernel_dir, kernel_dir.parent / "common", kernel_dir.parent / "headers")
    return sorted(
        (
            path
            for root in roots
            for path in root.glob("*.h")
            if not path.name.endswith("skel.h") and path.name not in EXCLUDED_HEADERS
        ),
        key=lambda path: str(path.relative_to(kernel_dir.parent)),
    )


def render_header(kernel_dir):
    digest = hashlib.sha256()
    features = set()
    header_defined = set()
    for path in shared_inputs(kernel_dir):
        data = path.read_bytes()
        digest.update(str(path.relative_to(kernel_dir.parent)).encode() + b"\0" + data + b"\0")
        features.update(re.findall(rb"\bHAVE_[A-Z0-9_]+\b", data))
        header_defined.update(re.findall(rb"^\s*#\s*define\s+(HAVE_[A-Z0-9_]+)", data, re.M))
    features = sorted(feature.decode() for feature in features - header_defined)
    lines = [
        "/* Generated by gen_abi_fingerprint.py; do not edit. */",
        "#ifndef LLB_ABI_FINGERPRINT_GENERATED_H",
        "#define LLB_ABI_FINGERPRINT_GENERATED_H",
        f'#define LLB_ABI_HEADERS_HASH "{digest.hexdigest()}"',
    ]
    for index, feature in enumerate(features):
        lines.extend([
            f"#ifdef {feature}",
            f'#define LLB_ABI_FEATURE_{index} "1"',
            "#else",
            f'#define LLB_ABI_FEATURE_{index} "0"',
            "#endif",
        ])
    lines.extend([
        "#define LLB_ABI_STR_(x) #x",
        "#define LLB_ABI_STR(x) LLB_ABI_STR_(x)",
        "#ifndef MAX_REAL_CPUS",
        '#define LLB_ABI_CPUS "16"',
        "#else",
        "#define LLB_ABI_CPUS LLB_ABI_STR(MAX_REAL_CPUS)",
        "#endif",
        '#define LLB_ABI_FINGERPRINT LLB_ABI_HEADERS_HASH ":" '
        + " ".join(f"LLB_ABI_FEATURE_{index}" for index in range(len(features)))
        + ' ":" LLB_ABI_CPUS',
        "#endif",
        "",
    ])
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser()
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--output")
    mode.add_argument("--list-inputs", action="store_true")
    args = parser.parse_args()
    kernel_dir = Path(__file__).resolve().parent
    if args.list_inputs:
        for path in shared_inputs(kernel_dir):
            print(path.relative_to(kernel_dir) if path.parent == kernel_dir else "../" + str(path.relative_to(kernel_dir.parent)))
        return
    output = Path(args.output)
    data = render_header(kernel_dir)
    if not output.exists() or output.read_text() != data:
        output.write_text(data)


if __name__ == "__main__":
    main()
